package opencraft.world.block;

/** Numeric identifiers for all registered block types. */
public final class BlockIds {

  /** Air block identifier. */
  public static final byte AIR = 0;

  /** Grass block identifier. */
  public static final byte GRASS = 1;

  /** Dirt block identifier. */
  public static final byte DIRT = 2;

  /** Stone block identifier. */
  public static final byte STONE = 3;

  /** Sand block identifier. */
  public static final byte SAND = 4;

  /** Wood block identifier. */
  public static final byte WOOD = 5;

  /** Leaves block identifier. */
  public static final byte LEAVES = 6;

  /** Water block identifier. */
  public static final byte WATER = 7;

  private BlockIds() {}
}
